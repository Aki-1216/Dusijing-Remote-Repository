# 2. 进阶层：通过 input() 获取用户输入的饮品名称和价格
drink_name = input("请输入您想购买的饮品名称：")
# 将输入的单价转换为浮点数（小数），方便后续计算
original_price = float(input("请输入该饮品的原价（元）："))

# 3. 挑战层：计算会员价（原价 × 0.8）
member_price = original_price * 0.8

# 4. 基础层与挑战层：输出结算详情（至少 5 行内容）
print("-" * 35)
